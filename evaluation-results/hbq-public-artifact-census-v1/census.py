"""Reconstruct the tracked public evaluation-file census at one Git commit."""
from __future__ import annotations

import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import subprocess

COMMIT = '989d75434c82d157e33913823c63a486467dd236'
ROOT = 'evaluation-results/'


def parse_tree(raw: bytes):
    """Parse Git's NUL-separated tree records without reading file content."""
    if raw and not raw.endswith(b'\0'):
        raise ValueError('incomplete Git tree listing')
    records = []
    for record in raw.split(b'\0')[:-1]:
        try:
            metadata, raw_path = record.split(b'\t', 1)
            mode, kind, oid, size = metadata.split()
            path = raw_path.decode('utf-8', errors='strict')
            oid_text = oid.decode('ascii')
            size_text = size.decode('ascii')
        except (ValueError, UnicodeDecodeError) as exc:
            raise ValueError('invalid Git tree record') from exc
        if (mode != b'100644' or kind != b'blob' or not re.fullmatch(r'[0-9a-f]{40}', oid_text)
                or not size_text.isdecimal() or not path.startswith(ROOT)
                or len(path.split('/')) < 3 or any(part in ('', '.', '..') for part in path.split('/'))):
            raise ValueError('unsupported path, mode or object identity')
        records.append({'path': path, 'git_blob_sha1': oid_text, 'bytes': int(size_text),
                        'result_directory': path.split('/')[1]})
    records.sort(key=lambda x: x['path'].encode('utf-8'))
    if len({row['path'] for row in records}) != len(records):
        raise ValueError('duplicate paths')
    return records


def generate(repo: Path):
    command = ['git', '-C', str(repo), 'ls-tree', '-r', '-l', '-z', COMMIT, '--', ROOT]
    raw = subprocess.run(command, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE).stdout
    rows = parse_tree(raw)
    if not rows:
        raise ValueError('empty or unavailable pinned tree')
    lines = b''.join((json.dumps(row, ensure_ascii=False, sort_keys=True, separators=(',', ':')) + '\n').encode('utf-8')
                     for row in rows)
    summary = {'schema':'tracked-public-evaluation-artifact-census-v1', 'source_commit':COMMIT,
               'scope':'tracked files under evaluation-results at source commit',
               'path_count':len(rows), 'result_directory_count':len({r['result_directory'] for r in rows}),
               'unique_git_blob_count':len({r['git_blob_sha1'] for r in rows}),
               'total_file_bytes_counting_each_path':sum(r['bytes'] for r in rows),
               'file_suffix_counts':dict(sorted(Counter(PurePosixPath(r['path']).suffix.lower() or '(none)'
                                                       for r in rows).items())),
               'manifest_sha256':hashlib.sha256(lines).hexdigest(),
               'limitations':['Git tree inventory only; no verdict, request, leaf or provider status inferred.',
                              'Untracked, ignored, private, deleted, external and later files are excluded.',
                              'Shared Git blob identity is not evidence of independent judgments.']}
    report = (json.dumps(summary, ensure_ascii=False, sort_keys=True, indent=2) + '\n').encode('utf-8')
    return lines, report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo', type=Path, required=True)
    parser.add_argument('--verify', action='store_true', help='compare against files alongside this script')
    parser.add_argument('--output-dir', type=Path, help='fresh existing destination for a new export')
    args = parser.parse_args()
    if args.verify == bool(args.output_dir):
        parser.error('choose exactly one of --verify or --output-dir')
    manifest, summary = generate(args.repo)
    directory = Path(__file__).resolve().parent if args.verify else args.output_dir
    for name, content in [('manifest.jsonl', manifest), ('summary.json', summary)]:
        path = directory / name
        if args.verify:
            if path.read_bytes() != content:
                raise ValueError(f'{name} differs from regenerated bytes')
        else:
            with path.open('xb') as out:
                out.write(content)
    print('Verified' if args.verify else 'Created', 'pinned public artifact census')


if __name__ == '__main__':
    main()
